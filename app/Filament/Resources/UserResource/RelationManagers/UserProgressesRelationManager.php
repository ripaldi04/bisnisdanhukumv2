class UserProgressesRelationManager extends RelationManager
{
    protected static string $relationship = 'userProgresses';

    public function form(Form $form): Form
    {
        return $form
            ->schema([]);
    }

    public function table(Table $table): Table
    {
        return $table
            ->recordTitleAttribute('is_completed')
            ->columns([
                TextColumn::make('subModule.title')
                    ->label('Sub Module')
                    ->searchable(),
                IconColumn::make('is_completed')
                    ->boolean()
                    ->label('Sudah mengerjakan?'),
                TextColumn::make('completed_at')
                    ->label('Waktu menyelesaikan')
                    ->dateTime()
            ])
            ->filters([
                //
            ])
            ->headerActions([
